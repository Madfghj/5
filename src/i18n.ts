export const dict: Record<Locale, Translations> = { ru, de, en, fr };

export type TranslationKey = {
  [K in keyof Translations]: Translations[K] extends string ? K : never;
}[keyof Translations];

/** Interpolate named values without evaluating markup or executable templates. */
export function text(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  return dict[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder,
  );
}

