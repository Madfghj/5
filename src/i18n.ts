/** Translate a server error code without exposing raw internal identifiers. */
export function errorText(locale: Locale, code: string): string {
  return text(locale, Object.prototype.hasOwnProperty.call(apiErrorKeys, code) ? apiErrorKeys[code] : 'error');
}

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && locales.some(({ code }) => code === value);
}
